/** Very rounded, "floating card" shape scale. */
val MintShapes = Shapes(
    extraSmall = RoundedCornerShape(10.dp),
    small = RoundedCornerShape(16.dp),
    medium = RoundedCornerShape(24.dp),
    large = RoundedCornerShape(32.dp),
    extraLarge = RoundedCornerShape(40.dp),
)

/** User-facing "reduce motion" switch, available anywhere in the tree. */
val LocalReducedMotion = staticCompositionLocalOf { false }

object Mint {
    val colors: MintColors
        @Composable @ReadOnlyComposable get() = LocalMintColors.current
    val reducedMotion: Boolean
        @Composable @ReadOnlyComposable get() = LocalReducedMotion.current
}

@Composable
fun MintlineTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    reducedMotion: Boolean = false,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val colorScheme = if (darkTheme) DarkScheme else LightScheme
    val mintColors = if (darkTheme) DarkMintColors else LightMintColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(
        LocalMintColors provides mintColors,
        LocalReducedMotion provides reducedMotion,
    ) {
        // Expressive motion (springs, squish, shape morphs) is implemented in
        // ui/components/Expressive.kt so it works on stable Material3.
        MaterialTheme(
            colorScheme = colorScheme,
            shapes = MintShapes,
            typography = Typography,
            content = content,
        )
    }
}
